// Package repodocs holds the deterministic checks that keep this repository
// navigable by a coding agent, plus the generator for the decision index.
//
// It exists because the four things it verifies all fail *silently*. A context
// file over Codex's project_doc_max_bytes is not truncated with an error: the
// deepest instructions simply stop existing. A skill location that drifted from
// a symlink into a copy does not warn: two clients just start reading different
// procedures. A hand-maintained index does not complain when a decision is
// missing from it: it only stops being trustworthy, and then stops being read.
// A moved page does not report its inbound links.
//
// Everything here therefore runs inside `make test`, which CI already runs, so
// no one has to remember a separate command.
package repodocs


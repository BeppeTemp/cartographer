// Package repodocs holds the deterministic checks that keep this repository
// navigable by a coding agent, plus the generators for the decision index and
// the code map.
//
// It exists because everything it verifies fails *silently*. A context file
// over Codex's project_doc_max_bytes is not truncated with an error: the
// deepest instructions simply stop existing. A skill whose frontmatter is not
// valid YAML is not reported: the client drops the skill and lists the others.
// A skill location that drifted from a symlink into a copy does not warn: two
// clients just start reading different procedures. A hand-maintained index does
// not complain when a decision is missing from it: it only stops being
// trustworthy, and then stops being read. A moved page does not report its
// inbound links, and a `D<n>` or a `docs/…` path in a comment is checked by
// nothing at all.
//
// Everything here therefore runs inside `make test`, which CI already runs, so
// no one has to remember a separate command.
package repodocs


func parseCIJobs(ciYAML string) ([]ciJob, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(ciYAML), &doc); err != nil {
		return nil, fmt.Errorf("parsing ci.yml: %w", err)
	}
	if len(doc.Content) == 0 {
		return nil, fmt.Errorf("ci.yml is empty")
	}
	jobs := mappingValue(doc.Content[0], "jobs")
	if jobs == nil || jobs.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("ci.yml has no jobs mapping")
	}
	var out []ciJob
	for i := 0; i+1 < len(jobs.Content); i += 2 {
		id, body := jobs.Content[i].Value, jobs.Content[i+1]
		j := ciJob{id: id, name: id}
		if n := mappingValue(body, "name"); n != nil {
			j.name = n.Value
		}
		if c := mappingValue(body, "if"); c != nil {
			j.cond = strings.Join(strings.Fields(c.Value), " ")
		}
		if n := mappingValue(body, "needs"); n != nil {
			if n.Kind == yaml.SequenceNode {
				for _, x := range n.Content {
					j.needs = append(j.needs, x.Value)
				}
			} else {
				j.needs = []string{n.Value}
			}
		}
		if steps := mappingValue(body, "steps"); steps != nil {
			for _, s := range steps.Content {
				r := mappingValue(s, "run")
				if r == nil {
					continue
				}
				run := strings.TrimSpace(r.Value)
				if m := makeStep.FindStringSubmatch(run); m != nil {
					j.makeSteps = append(j.makeSteps, m[1])
				} else if makeWord.MatchString(run) {
					j.unreadSteps = append(j.unreadSteps, run)
				}
			}
		}
		out = append(out, j)
	}
	return out, nil
}

func mappingValue(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// shellWords reads one `NAME="..."` assignment of scripts/signoff.sh.
func shellWords(sh, name string) ([]string, error) {
	m := regexp.MustCompile(`(?m)^` + name + `="([^"]*)"$`).FindStringSubmatch(sh)
	if m == nil {
		return nil, fmt.Errorf("scripts/signoff.sh has no %s=\"...\" line", name)
	}
	return strings.Fields(m[1]), nil
}

var matrixRef = regexp.MustCompile(`\$\{\{\s*matrix\.([A-Za-z0-9_-]+)\s*\}\}`)

// RenderRunsWhere builds the generated block of docs/testing.md from the text of ci.yml and
// scripts/signoff.sh: one row per job of ci.yml, in file order.
func RenderRunsWhere(ciYAML, signoffSh string) (string, error) {
	jobs, err := parseCIJobs(ciYAML)
	if err != nil {
		return "", err
	}
	hostedJobs, err := shellWords(signoffSh, "HOSTED_JOBS")
	if err != nil {
		return "", err
	}
	targets, err := shellWords(signoffSh, "TARGETS")
	if err != nil {
		return "", err
	}
	web, err := shellWords(signoffSh, "WEB_TARGET")
	if err != nil {
		return "", err
	}

	byID := map[string]ciJob{}
	for _, j := range jobs {
		byID[j.id] = j
	}
	for id := range buildHostCells {
		if _, ok := byID[id]; !ok {
			return "", fmt.Errorf("the build-host column names job %q, which ci.yml no longer defines", id)
		}
	}
	// The second table compares the make steps of `test` with TARGETS: a step it cannot read
	// would drop out of that comparison in silence.
	if u := byID["test"].unreadSteps; len(u) > 0 {
		return "", fmt.Errorf("job test: a run: step calls make in a form the table cannot read "+
			"(one `make <target>` per step): %q", u[0])
	}
	status, ok := byID["main-status"]
	if !ok {
		return "", fmt.Errorf("ci.yml has no main-status job: the push column cannot say which jobs are in main's verdict")
	}
	// main's verdict: main-status and everything it needs; a job outside it runs on the push
	// and turns nothing red.
	verdict := map[string]bool{}
	var watch func(id string)
	watch = func(id string) {
		if verdict[id] {
			return
		}
		verdict[id] = true
		for _, n := range byID[id].needs {
			watch(n)
		}
	}
	watch(status.id)
	// The jobs a hosted gate waits for: those of HOSTED_JOBS (a name, or a matrix leg of it,
	// as hosted_verdict reads them) and everything they need.
	waited := map[string]bool{}
	var mark func(id string)
	mark = func(id string) {
		if waited[id] {
			return
		}
		waited[id] = true
		for _, n := range byID[id].needs {
			mark(n)
		}
	}
	for _, h := range hostedJobs {
		found := false
		for _, j := range jobs {
			if j.name == h || strings.HasPrefix(j.name, h+" (") {
				// hosted_verdict reads a skipped job of HOSTED_JOBS as red, and a matrix job with no
				// aggregator of that name as missing (scripts/signoff.sh): a leg a dispatch skips is
				// refused like the job itself.
				if on, ok := ciConditions[j.cond]; ok && on.dispatch == "no" {
					return "", fmt.Errorf("HOSTED_JOBS names %q, and its job %q is skipped on a dispatched run "+
						"by its if: every hosted gate would be red", h, j.name)
				}
				mark(j.id)
				found = true
			}
		}
		if !found {
			return "", fmt.Errorf("HOSTED_JOBS names %q, which is no job of ci.yml", h)
		}
	}
	required := map[string]bool{}
	for _, c := range RequiredChecks {
		required[c] = true
	}

	var b strings.Builder
	b.WriteString("| Job of `ci.yml` | Contributor's PR | Maintainer's PR | Train gate (hosted) | Train gate (build host) | Push to `main` | Required check |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, j := range jobs {
		on, ok := ciConditions[j.cond]
		if !ok {
			return "", fmt.Errorf("job %s: its if: expression is not in the table of internal/repodocs (ciConditions), "+
				"add where it runs: %s", j.id, j.cond)
		}
		hosted := "no"
		switch {
		case on.dispatch == "no":
		case waited[j.id]:
			hosted = "yes"
		default:
			hosted = "runs, not waited for"
		}
		host := "no"
		if c, ok := buildHostCells[j.id]; ok {
			host = c
			if strings.Contains(c, "%s") {
				words := targets
				if j.id != "test" {
					words = web
				}
				host = fmt.Sprintf(c, strings.Join(words, " "))
			}
		}
		push := on.push
		if push != "no" && !verdict[j.id] {
			push += ", outside the verdict"
		}
		req := "no"
		if required[j.name] {
			req = "yes"
		}
		name := matrixRef.ReplaceAllString(j.name, "<$1>")
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s | %s |\n",
			name, on.contributor, on.maintainer, hosted, host, push, req)
	}

	// The steps of `test` a build-host gate leaves out: its make steps not among TARGETS.
	inTargets := map[string]bool{}
	for _, t := range targets {
		inTargets[t] = true
	}
	var left []string
	for _, s := range byID["test"].makeSteps {
		if !inTargets[s] {
			left = append(left, "`make "+s+"`")
		}
	}
	if len(left) == 0 {
		left = []string{"none"}
	}
	b.WriteString("\n| Build-host gate | Make targets |\n|---|---|\n")
	fmt.Fprintf(&b, "| Runs | `make %s`, and `make %s` when the frontend changed |\n",
		strings.Join(targets, " "), strings.Join(web, " "))
	fmt.Fprintf(&b, "| Does not run, of the `test` job's steps (the hosted gate does) | %s |\n", strings.Join(left, ", "))
	return b.String(), nil
}

// BlockBody returns the text between begin and end, exclusive of the markers.
// It insists on exactly one of each, in order: a duplicated marker pair is how a
// generated block silently stops being the one that is checked.
func BlockBody(content, begin, end string) (string, error) {
	if n := strings.Count(content, begin); n != 1 {
		return "", fmt.Errorf("found %d begin markers, want exactly 1:\n  %s", n, begin)
	}
	if n := strings.Count(content, end); n != 1 {
		return "", fmt.Errorf("found %d end markers, want exactly 1:\n  %s", n, end)
	}
	i := strings.Index(content, begin) + len(begin)
	j := strings.Index(content, end)
	if j < i {
		return "", fmt.Errorf("the end marker precedes the begin marker")
	}
	return content[i:j], nil
}

// StripGeneratedBlocks removes every generated block this package owns, markers
// included, so a budget can be measured on the hand-written text alone.
func StripGeneratedBlocks(content string) string {
	for _, pair := range [][2]string{{CodeMapBegin, CodeMapEnd}, {IndexBegin, IndexEnd}} {
		i := strings.Index(content, pair[0])
		j := strings.Index(content, pair[1])
		if i < 0 || j < i {
			continue
		}
		content = content[:i] + content[j+len(pair[1]):]
	}
	return content
}

// decisionRef matches this repository's reference convention: the bare `D<n>`,
// no path, so a reworded title does not break it. Nothing about it is checked by
// the compiler, which is why CitedDecisions exists.
var decisionRef = regexp.MustCompile(`\bD([0-9]{1,3})\b`)

// CitedDecisions returns every decision number referenced from the corpus, with
// the files that reference it, so a reference that no longer resolves can be
// named at every site rather than one.
func CitedDecisions(root string) (map[int][]string, error) {
	files, err := TextFiles(root)
	if err != nil {
		return nil, err
	}

	found := map[int][]string{}
	for _, rel := range files {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			return nil, err
		}
		seen := map[int]bool{}
		for _, m := range decisionRef.FindAllStringSubmatch(string(data), -1) {
			n, err := strconv.Atoi(m[1])
			if err != nil || seen[n] {
				continue
			}
			seen[n] = true
			found[n] = append(found[n], rel)
		}
	}
	return found, nil
}

// docPathRef matches a repository-relative path into the documentation surface.
// The character class excludes `<` and `>`, so the placeholder forms this
// repository writes on purpose — `docs/decisions/D<n>-<slug>.md` — are not
// mistaken for pointers. Only this repository's own skills are named: the
// product's tests use `.claude/skills/<fixture>` paths that are not ours.
var docPathRef = regexp.MustCompile(`(?:docs|\.claude/skills/cartographer-(?:audit-clients|develop-live|implement-plan|propose-plan|review-pr))/[A-Za-z0-9._/-]+\.md`)

// CitedDocPaths returns every documentation path cited anywhere in the corpus,
// with the files citing it. Unlike the markdown-link check this reads *any* text,
// which is the only way to see the pointers that live in Go and shell comments —
// where a page rename leaves them dangling with nothing to report it.
func CitedDocPaths(root string) (map[string][]string, error) {
	files, err := TextFiles(root)
	if err != nil {
		return nil, err
	}

	found := map[string][]string{}
	for _, rel := range files {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			return nil, err
		}
		seen := map[string]bool{}
		for _, m := range docPathRef.FindAllString(string(data), -1) {
			if seen[m] {
				continue
			}
			seen[m] = true
			found[m] = append(found[m], rel)
		}
	}
	return found, nil
}

// SkillFrontmatter is the frontmatter of a SKILL.md, parsed by the same
// spec-compliant YAML parser a client uses.
type SkillFrontmatter struct {
	Name        string `yaml:"name"`
	Description string `yaml:"description"`
}

// ParseSkillFrontmatter reads a SKILL.md and parses its frontmatter with
// gopkg.in/yaml.v3.
//
// The parser is the point of this function. A hand-rolled "split on the first
// colon" reader accepts frontmatter that no client can load — an unquoted plain
// scalar containing ": " is a YAML syntax error, and the observed behaviour is
// that the client drops the skill and lists the others, with no message anywhere
// (D207). Cartographer's own OKF frontmatter reader is deliberately not used
// here either: it is lenient by design for KB concepts, and the question this
// asks is what a *client* will accept.
func ParseSkillFrontmatter(path string) (*SkillFrontmatter, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	text := string(data)
	if !strings.HasPrefix(text, "---\n") {
		return nil, fmt.Errorf("no YAML frontmatter: the file must start with a `---` line")
	}
	end := strings.Index(text[4:], "\n---")
	if end < 0 {
		return nil, fmt.Errorf("the YAML frontmatter is never closed by a `---` line")
	}

	var fm SkillFrontmatter
	if err := yaml.Unmarshal([]byte(text[4:4+end]), &fm); err != nil {
		return nil, fmt.Errorf("the frontmatter is not valid YAML, so a client will "+
			"skip this skill without reporting anything: %w\n"+
			"  the usual cause is an unquoted value containing \": \" — quote it, or "+
			"replace the colon with an em dash", err)
	}
	return &fm, nil
}

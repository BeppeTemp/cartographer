// Budgets. These are not style preferences: each one is a limit a real client
// enforces, and the lowest of them is what the repository has to respect.
const (
	// Codex concatenates the AGENTS.md chain from the repository root down to
	// the working directory and stops adding files once the combined size
	// reaches project_doc_max_bytes, 32 KiB by default. What gets dropped is
	// the *deepest* file, i.e. the guidance closest to the code.
	MaxChainBytes = 32 * 1024

	// Antigravity documents a 12,000-character ceiling per rules file. It is
	// the lowest per-file limit among the four supported clients, so it is the
	// one that binds.
	MaxRootChars = 12000

	// Not a client limit but an adherence one: instruction-following degrades
	// as the file grows, and every client's guidance converges on "keep it
	// short". 120 lines is the pattern's own threshold.
	MaxRootLines = 120

	// Skill frontmatter, per Kiro's rules — the strictest of the four, so a
	// skill written to them is valid everywhere.
	MaxSkillNameChars        = 64
	MaxSkillDescriptionChars = 1024
)


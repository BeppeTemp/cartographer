//go:build !windows

package provisioning

import (
	"strings"

	"github.com/BeppeTemp/cartographer/internal/configurator"
)

// The POSIX half of the bootstrap script (D60). The name and the body are
// build-tagged rather than switched on runtime.GOOS (docs/conventions.md
// §Dependencies): the script is generated for the machine it will run on, and
// there is no case in which a client materializes the other platform's script.
//
// The hook's content hash (bootstrapHookFor, bootstrap.go) is computed from these
// constants, so it becomes platform-dependent by construction. Nothing may pin its literal
// value — a test that needs it must derive it the same way.

// bootstrapScriptName is the generated script's file name inside the hook's
// destination directory (DestDir("hook", BootstrapHookName, provider)).
const bootstrapScriptName = "bootstrap.sh"

// bootstrapScriptContent is the deterministic body of the generated bootstrap
// script — identical for every provider. The sync is silent (all output
// discarded) and the script always exits 0: a sync failure (e.g. server down)
// must never break session startup. `cartographer sync` itself already runs
// over an HTTP client with a bounded timeout (internal/client, 30s) — no extra
// timeout needed here.
//
// The one line whose stdout is kept is `update notice` (D254): it prints
// nothing unless a newer release exists, and a SessionStart hook's stdout is
// what reaches the agent's context. Its stderr is discarded like the sync's.
// When generating for Antigravity, --channel antigravity is passed so update
// notice outputs protojson (injectSteps) as required by Google Antigravity.
const bootstrapScriptContent = `#!/bin/sh
# cartographer-bootstrap — generated by Cartographer (WP4/D60), do not edit.
command -v cartographer >/dev/null 2>&1 || exit 0
err=$(cartographer sync --if-older-than 10m 2>&1 >/dev/null) || {
  # A binary older than the script rejects the flag: sync plainly, once.
  case "$err" in
  *"flag provided but not defined: -if-older-than"*) cartographer sync >/dev/null 2>&1 || true ;;
  esac
}
cartographer update notice 2>/dev/null || true
`

// bootstrapScriptContentFor bakes the provider into the sync (--client), so a
// session start syncs only its own client, and the freshness gate
// (--if-older-than 10m) in front of it: inside the window the sync exits at
// once, before the client lock and any network call. A provider that is not
// connected falls back to the plain sync inside `sync` itself (cmdSync).
func bootstrapScriptContentFor(provider configurator.Provider) string {
	content := bootstrapScriptContent
	if provider == configurator.ProviderAntigravity {
		content = strings.Replace(content, "cartographer update notice ", "cartographer update notice --channel antigravity ", 1)
	}
	return strings.ReplaceAll(content, "cartographer sync", "cartographer sync --client "+string(provider))
}

package provisioning

import (
	"fmt"
	"strings"
)

// generatedArtifactFiles returns the files Cartographer adds to an artifact's
// materialized directory beyond the KB's own: SOURCE.env (D316) for a KB skill.
//
// A KB skill that already ships a file with a generated name is a collision:
// overwriting it would silently destroy KB content, and delivering both is
// impossible. That one artifact fails with a warning naming it; the rest of
// the sync completes, and the collision persists (nothing is recorded in the
// lockfile) until the KB is fixed.
func generatedArtifactFiles(a Artifact, opts ApplyOptions, files []ArtifactFile) (generated []ArtifactFile, warning string, ok bool) {
	if a.Kind != "skill" {
		return nil, "", true
	}
	if kbName, fromKB := kbSourceName(a); fromKB {
		generated = []ArtifactFile{{Path: skillSourceEnvFile, Content: skillSourceEnv(kbName, opts.KBRoots[kbName])}}
	}
	for _, g := range generated {
		for _, f := range files {
			if strings.EqualFold(strings.TrimPrefix(f.Path, "./"), g.Path) {
				return nil, fmt.Sprintf("skill %q ships its own %s: not delivered to this client: Cartographer generates that file (rename it in the KB)", a.Name, g.Path), false
			}
		}
	}
	return generated, "", true
}

// skillSourceEnvFile is written next to a materialized KB skill's SKILL.md so
// a script the skill ships can find its KB without parsing local config
// (D316). It exists only in the client directory, never in the KB: the values
// are this deployment's, not content.
const skillSourceEnvFile = "SOURCE.env"

// skillSourceEnv renders SOURCE.env: KEY=VALUE lines a script can `source` or
// grep. CARTOGRAPHER_KB_ROOT is written only when the KB's root is on this
// machine (a local deployment, or the server's own sync_apply): a client fed
// over HTTP has no local copy of the KB, and a server path would point at
// nothing. Values are not shell-quoted; a consumer that may meet a path with
// spaces quotes it. Deterministic, so an unchanged skill re-materializes
// byte-identically.
func skillSourceEnv(kbName, kbRoot string) []byte {
	var sb strings.Builder
	sb.WriteString("# Generated by Cartographer at sync: the KB this skill came from.\n")
	fmt.Fprintf(&sb, "CARTOGRAPHER_KB_NAME=%s\n", kbName)
	if kbRoot != "" && !strings.ContainsAny(kbRoot, "\n\r") {
		fmt.Fprintf(&sb, "CARTOGRAPHER_KB_ROOT=%s\n", kbRoot)
	}
	return []byte(sb.String())
}
